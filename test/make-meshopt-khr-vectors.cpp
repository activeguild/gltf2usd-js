// Generates test/meshopt-khr-vectors.js: KHR_meshopt_compression test vectors (vertex codec v1,
// COLOR filter, index codecs) encoded by meshoptimizer and decoded by its *scalar* decoder.
// Not part of the build; run by hand when the vectors need to change:
//
//   # meshoptimizer v1.3: src/{meshoptimizer.h,vertexcodec.cpp,vertexfilter.cpp,indexcodec.cpp}
//   c++ -std=c++11 -O1 -DMESHOPTIMIZER_NO_SIMD -I<src> test/make-meshopt-khr-vectors.cpp \
//     <src>/vertexcodec.cpp <src>/vertexfilter.cpp <src>/indexcodec.cpp -o make-vectors
//   ./make-vectors > test/meshopt-khr-vectors.js
//
// MESHOPTIMIZER_NO_SIMD selects the scalar decoder: the SIMD filters may differ by one unit
// (the spec allows it), and src/meshopt.js follows the scalar code.

#include "meshoptimizer.h"

#include <math.h>
#include <stdio.h>
#include <string.h>
#include <string>
#include <vector>

static unsigned int seed = 12345;
static unsigned int rnd() { return seed = seed * 1664525u + 1013904223u; }
static float frnd() { return float(rnd() >> 8) / float(1 << 24); } // [0, 1)

static std::string base64(const unsigned char* p, size_t n) {
  static const char* t = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  std::string s;
  for (size_t i = 0; i < n; i += 3) {
    unsigned int v = p[i] << 16 | (i + 1 < n ? p[i + 1] << 8 : 0) | (i + 2 < n ? p[i + 2] : 0);
    s += t[v >> 18 & 63];
    s += t[v >> 12 & 63];
    s += i + 1 < n ? t[v >> 6 & 63] : '=';
    s += i + 2 < n ? t[v & 63] : '=';
  }
  return s;
}

static bool first = true;

static void emit(const char* name, size_t count, size_t stride, const char* mode, const char* filter,
                 const std::vector<unsigned char>& encoded, const std::vector<unsigned char>& expected) {
  printf("%s  {\n    \"name\": \"%s\",\n    \"count\": %zu,\n    \"byteStride\": %zu,\n    \"mode\": \"%s\",\n",
         first ? "" : ",\n", name, count, stride, mode);
  if (strcmp(filter, "NONE")) printf("    \"filter\": \"%s\",\n", filter);
  printf("    \"encoded\": \"%s\",\n    \"expected\": \"%s\"\n  }", base64(encoded.data(), encoded.size()).c_str(),
         base64(expected.data(), expected.size()).c_str());
  first = false;
}

// Encode `data` (already filter-encoded) with the vertex codec, decode it with the scalar
// decoder (+ filter) and emit the pair.
static void vertex(const char* name, const void* data, size_t count, size_t stride, int level, int version,
                   const char* filter = "NONE") {
  std::vector<unsigned char> enc(meshopt_encodeVertexBufferBound(count, stride));
  enc.resize(meshopt_encodeVertexBufferLevel(enc.data(), enc.size(), data, count, stride, level, version));
  if (enc.empty()) { fprintf(stderr, "%s: encode failed\n", name); return; }
  std::vector<unsigned char> dec(count * stride);
  if (meshopt_decodeVertexBuffer(dec.data(), count, stride, enc.data(), enc.size()) != 0) {
    fprintf(stderr, "%s: decode failed\n", name);
    return;
  }
  if (memcmp(dec.data(), data, dec.size())) fprintf(stderr, "%s: round trip differs\n", name);
  if (!strcmp(filter, "OCTAHEDRAL")) meshopt_decodeFilterOct(dec.data(), count, stride);
  if (!strcmp(filter, "QUATERNION")) meshopt_decodeFilterQuat(dec.data(), count, stride);
  if (!strcmp(filter, "EXPONENTIAL")) meshopt_decodeFilterExp(dec.data(), count, stride);
  if (!strcmp(filter, "COLOR")) meshopt_decodeFilterColor(dec.data(), count, stride);
  emit(name, count, stride, "ATTRIBUTES", filter, enc, dec);
}

int main() {
  printf("// Generated by test/make-meshopt-khr-vectors.cpp from meshoptimizer v1.3 (vertex codec v1,\n");
  printf("// scalar decoder: MESHOPTIMIZER_NO_SIMD). `expected` is the decoder's output after the filter.\n");
  printf("// Used by test/run.js to check src/meshopt.js for KHR_meshopt_compression.\n");
  printf("export const KHR_VECTORS = [\n");

  // Float positions on a sphere (XOR channels at level 3).
  {
    const size_t n = 300;
    std::vector<float> v(n * 3);
    for (size_t i = 0; i < n; i++) {
      float a = float(i) * 0.37f, b = float(i) * 0.011f;
      v[i * 3 + 0] = cosf(a) * sinf(b) * 2.5f;
      v[i * 3 + 1] = cosf(b) * 2.5f + 10.f;
      v[i * 3 + 2] = sinf(a) * sinf(b) * 2.5f;
    }
    vertex("v1 float positions level 3", v.data(), n, 12, 3, 1);
    vertex("v1 float positions level 2", v.data(), n, 12, 2, 1);
    vertex("v1 float positions level 0", v.data(), n, 12, 0, 1);
  }
  // Float UVs.
  {
    const size_t n = 517;
    std::vector<float> v(n * 2);
    for (size_t i = 0; i < n; i++) {
      v[i * 2 + 0] = float(i % 23) / 22.f;
      v[i * 2 + 1] = float(i / 23) / 22.f + frnd() * 0.001f;
    }
    vertex("v1 float uvs level 3", v.data(), n, 8, 3, 1);
  }
  // Quantized int16 positions (16-bit delta channels).
  {
    const size_t n = 300;
    std::vector<short> v(n * 4);
    for (size_t i = 0; i < n; i++) {
      v[i * 4 + 0] = short(int(i * 97) - 15000);
      v[i * 4 + 1] = short(cosf(float(i) * 0.05f) * 30000.f);
      v[i * 4 + 2] = short(int(i * i) % 60000 - 30000);
      v[i * 4 + 3] = 0;
    }
    vertex("v1 int16 positions level 3", v.data(), n, 8, 3, 1);
    vertex("v1 int16 positions level 2", v.data(), n, 8, 2, 1);
  }
  // Slowly varying bytes (1-bit groups), pure noise (literal), constants (zero control).
  {
    const size_t n = 260;
    std::vector<unsigned char> smooth(n * 4), noise(n * 8), constant(n * 16);
    for (size_t i = 0; i < n; i++) {
      for (int k = 0; k < 4; k++) smooth[i * 4 + k] = (unsigned char)((i * (k + 1)) / 7 + (rnd() % 16 == 0));
      for (int k = 0; k < 8; k++) noise[i * 8 + k] = (unsigned char)(rnd() >> 24);
      for (int k = 0; k < 16; k++) constant[i * 16 + k] = (unsigned char)(k * 17);
    }
    vertex("v1 smooth bytes", smooth.data(), n, 4, 3, 1);
    vertex("v1 noise bytes", noise.data(), n, 8, 3, 1);
    vertex("v1 constant bytes", constant.data(), n, 16, 3, 1);
    vertex("v1 one vertex", noise.data(), 1, 8, 3, 1);
    vertex("v1 17 vertices", smooth.data(), 17, 4, 3, 1);
  }
  // 32-bit words with noise in a bit field that straddles bytes (XOR channels with rotation).
  {
    const size_t n = 400;
    std::vector<unsigned int> v(n * 2);
    for (size_t i = 0; i < n; i++) {
      v[i * 2 + 0] = 0x3f800000u | (rnd() & 0x0ff0u);
      v[i * 2 + 1] = 0x00100000u ^ (rnd() & 0x00ffc000u);
    }
    vertex("v1 bit fields level 3", v.data(), n, 8, 3, 1);
  }
  // Interleaved mixed data, several blocks (stride 32 → 256 vertices per block).
  {
    const size_t n = 700;
    std::vector<unsigned char> v(n * 32);
    for (size_t i = 0; i < n; i++) {
      float f[3] = {float(i) * 0.01f, sinf(float(i) * 0.1f), 1.f};
      memcpy(&v[i * 32], f, 12);
      unsigned short s[4] = {(unsigned short)(i * 3), (unsigned short)(i / 3), 0, 65535};
      memcpy(&v[i * 32 + 12], s, 8);
      for (int k = 20; k < 32; k++) v[i * 32 + k] = (unsigned char)(k < 26 ? i / 5 : rnd() >> 24);
    }
    vertex("v1 interleaved multi-block", v.data(), n, 32, 3, 1);
    vertex("v0 interleaved multi-block", v.data(), n, 32, 2, 0);
  }
  // COLOR filter: 8-bit (K = 8 and 6) and 16-bit (K = 12 and 16).
  {
    const size_t n = 200;
    std::vector<float> c(n * 4);
    for (size_t i = 0; i < n; i++) {
      c[i * 4 + 0] = 0.5f + 0.5f * sinf(float(i) * 0.07f);
      c[i * 4 + 1] = float(i) / float(n - 1);
      c[i * 4 + 2] = frnd();
      c[i * 4 + 3] = i % 5 == 0 ? 1.f : frnd();
    }
    std::vector<unsigned char> c8(n * 4);
    std::vector<unsigned short> c16(n * 4);
    meshopt_encodeFilterColor(c8.data(), n, 4, 8, c.data());
    vertex("v1 COLOR uint8 K=8", c8.data(), n, 4, 3, 1, "COLOR");
    meshopt_encodeFilterColor(c8.data(), n, 4, 6, c.data());
    vertex("v1 COLOR uint8 K=6", c8.data(), n, 4, 3, 1, "COLOR");
    meshopt_encodeFilterColor(c16.data(), n, 8, 12, c.data());
    vertex("v1 COLOR uint16 K=12", c16.data(), n, 8, 3, 1, "COLOR");
    meshopt_encodeFilterColor(c16.data(), n, 8, 16, c.data());
    vertex("v1 COLOR uint16 K=16", c16.data(), n, 8, 3, 1, "COLOR");
    meshopt_encodeFilterColor(c8.data(), n, 4, 8, c.data());
    vertex("v0 COLOR uint8 K=8", c8.data(), n, 4, 2, 0, "COLOR");
  }
  // The EXT filters on the v1 codec.
  {
    const size_t n = 150;
    std::vector<float> nrm(n * 4), quat(n * 4), pos(n * 3);
    for (size_t i = 0; i < n; i++) {
      float a = float(i) * 0.3f, b = float(i) * 0.021f - 1.5f;
      nrm[i * 4 + 0] = cosf(a) * cosf(b), nrm[i * 4 + 1] = sinf(b), nrm[i * 4 + 2] = sinf(a) * cosf(b), nrm[i * 4 + 3] = i % 2 ? 1.f : -1.f;
      float h = float(i) * 0.05f;
      quat[i * 4 + 0] = sinf(h) * 0.6f, quat[i * 4 + 1] = sinf(h) * 0.8f, quat[i * 4 + 2] = 0.f, quat[i * 4 + 3] = cosf(h);
      pos[i * 3 + 0] = float(i) * 0.125f - 3.f, pos[i * 3 + 1] = sinf(h) * 1000.f, pos[i * 3 + 2] = 1e-3f * float(i);
    }
    std::vector<signed char> o8(n * 4);
    std::vector<short> o16(n * 4), q(n * 4);
    std::vector<int> e(n * 3);
    meshopt_encodeFilterOct(o8.data(), n, 4, 8, nrm.data());
    vertex("v1 OCTAHEDRAL int8", o8.data(), n, 4, 3, 1, "OCTAHEDRAL");
    meshopt_encodeFilterOct(o16.data(), n, 8, 12, nrm.data());
    vertex("v1 OCTAHEDRAL int16", o16.data(), n, 8, 3, 1, "OCTAHEDRAL");
    meshopt_encodeFilterQuat(q.data(), n, 8, 12, quat.data());
    vertex("v1 QUATERNION", q.data(), n, 8, 3, 1, "QUATERNION");
    meshopt_encodeFilterExp(e.data(), n, 12, 15, pos.data(), meshopt_EncodeExpSharedComponent);
    vertex("v1 EXPONENTIAL", e.data(), n, 12, 3, 1, "EXPONENTIAL");
  }
  // Index codecs (version 1 headers 0xe1 / 0xd1, which KHR_meshopt_compression requires).
  {
    std::vector<unsigned int> tri;
    const unsigned int w = 9;
    for (unsigned int y = 0; y < 7; y++)
      for (unsigned int x = 0; x < w - 1; x++) {
        unsigned int a = y * w + x, b = a + 1, c = a + w, d = c + 1;
        tri.insert(tri.end(), {a, c, b, b, c, d});
      }
    tri.insert(tri.end(), {70000, 3, 69999}); // forces explicit indices with 32-bit values
    std::vector<unsigned char> enc(meshopt_encodeIndexBufferBound(tri.size(), 70001));
    enc.resize(meshopt_encodeIndexBuffer(enc.data(), enc.size(), tri.data(), tri.size()));
    std::vector<unsigned int> dec(tri.size());
    if (meshopt_decodeIndexBuffer(dec.data(), tri.size(), 4, enc.data(), enc.size()) != 0) fprintf(stderr, "triangles: decode failed\n");
    emit("TRIANGLES uint32", tri.size(), 4, "TRIANGLES", "NONE", enc, std::vector<unsigned char>((unsigned char*)dec.data(), (unsigned char*)(dec.data() + dec.size())));

    tri.resize(tri.size() - 3);
    enc.assign(meshopt_encodeIndexBufferBound(tri.size(), 63), 0);
    enc.resize(meshopt_encodeIndexBuffer(enc.data(), enc.size(), tri.data(), tri.size()));
    std::vector<unsigned short> dec16(tri.size());
    if (meshopt_decodeIndexBuffer(dec16.data(), tri.size(), 2, enc.data(), enc.size()) != 0) fprintf(stderr, "triangles16: decode failed\n");
    emit("TRIANGLES uint16", tri.size(), 2, "TRIANGLES", "NONE", enc, std::vector<unsigned char>((unsigned char*)dec16.data(), (unsigned char*)(dec16.data() + dec16.size())));

    std::vector<unsigned int> seq;
    for (unsigned int i = 0; i < 40; i++) seq.push_back(i % 2 ? 1000 - i : i * 3);
    enc.assign(meshopt_encodeIndexSequenceBound(seq.size(), 1001), 0);
    enc.resize(meshopt_encodeIndexSequence(enc.data(), enc.size(), seq.data(), seq.size()));
    std::vector<unsigned short> decs(seq.size());
    if (meshopt_decodeIndexSequence(decs.data(), seq.size(), 2, enc.data(), enc.size()) != 0) fprintf(stderr, "sequence: decode failed\n");
    emit("INDICES uint16", seq.size(), 2, "INDICES", "NONE", enc, std::vector<unsigned char>((unsigned char*)decs.data(), (unsigned char*)(decs.data() + decs.size())));
  }
  printf("\n];\n");
  return 0;
}
